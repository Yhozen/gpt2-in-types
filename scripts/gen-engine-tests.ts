// Generates tests/types/engine.gen.ts: type-level checks of the engine against
// the integer reference (src/reference/int.ts), stage by stage. Each check is
// its own statement, well under the CLI's ~5M-instantiation budget.
// Run: node scripts/gen-engine-tests.ts
import { readFileSync, writeFileSync } from "node:fs";
import * as ref from "../src/reference/int.ts";

const root = new URL("../", import.meta.url);
const p = JSON.parse(readFileSync(new URL("model/program.json", root), "utf8")) as ref.Program;
const vec = (v: number[]) => `[${v.map((x) => `ToS<${x}>`).join(", ")}]`;
const embed = (t: number, pos: number) =>
  p.etok[t]!.map((v, i) => Math.max(-255, Math.min(255, v + p.epos[pos]![i]!)));

const checks: string[] = [];
const check = (name: string, actual: string, expected: string) =>
  checks.push(`export type ${name} = Expect<Equal<${actual}, ${expected}>>;`);

// Embedding and LayerNorm for a spread of tokens and positions.
for (const [t, pos] of [
  [0, 0],
  [30, 0],
  [27, 1],
  [62, 13],
  [12, 40],
  [45, 63],
] as const) {
  check(`Embed_${t}_${pos}`, `E.Embed<${t}, ${pos}>`, vec(embed(t, pos)));
  check(
    `LayerNorm_${t}_${pos}`,
    `E.LayerNorm<E.Embed<${t}, ${pos}>>`,
    vec(ref.layerNorm(embed(t, pos), p)),
  );
}

// Final residual stream of every position of a short sequence (all blocks, KV cache).
const tokens = ref.encode(p, "Wherefore");
const cache = p.layers.map(() => ({ k: [] as number[][][], v: [] as number[][][] }));
const residuals = tokens.map((t, pos) => ref.forward(p, t, pos, cache));
check("Trace", `E.Trace<[${tokens.join(", ")}]>`, `[${residuals.map(vec).join(",\n  ")}]`);

// Whole generations, both decoding modes.
for (const [prompt, n] of [
  ["Once", 3],
  ["Tom ", 3],
] as const) {
  for (const mode of ["sample", "greedy"] as const) {
    const text = ref.decode(p, ref.generate(p, ref.encode(p, prompt), n, mode));
    check(
      `Generate_${prompt.replace(/\W/g, "")}_${mode}`,
      `E.Generate<${JSON.stringify(prompt)}, ${n}, "${mode}">`,
      JSON.stringify(text),
    );
  }
}

// Seeded generations, including wraparound and continuation across checkpoints.
for (const seed of [1, p.config.block_size - 1]) {
  const expected = JSON.stringify(
    ref.decode(p, ref.generate(p, ref.encode(p, "Once"), 3, "sample", seed)),
  );
  check(`Seed_${seed}`, `E.Generate<"Once", 3, "sample", ${seed}>`, expected);
  check(
    `Seed_${seed}_steps`,
    `E.Output<E.Steps<E.Steps<E.Start<"Once">, 1, "sample", ${seed}>, 2, "sample", ${seed}>>`,
    expected,
  );
  check(
    `Seed_${seed}_advance`,
    `E.Output<E.Advance<E.Advance<E.Start<"Once">, 3, "sample", ${seed}>, 3, "sample", ${seed}>>`,
    expected,
  );
}
check(
  "Greedy_ignores_seed",
  `E.Generate<"Once", 3, "greedy", ${p.config.block_size - 1}>`,
  JSON.stringify(ref.decode(p, ref.generate(p, ref.encode(p, "Once"), 3, "greedy"))),
);

// Tokenization: greedy longest match, as the reference.
for (const [name, text] of [
  ["story", 'Once upon a time, there was a little girl named Lily. "Hello!" she said.'],
  ["words", "The friends wanted something together"],
  ["odd", "Zq x-y;:  ?!\n'A"],
] as const) {
  check(
    `Encode_${name}`,
    `E.Encode<${JSON.stringify(text)}>`,
    `[${ref.encode(p, text).join(", ")}]`,
  );
}

// Prompts the model cannot encode become readable errors, not `never` or `any`.
check(
  "Error_unknown_character",
  `E.Generate<"3 pigs", 2>`,
  JSON.stringify("Error: the character '3' is not in the model's vocabulary"),
);
check("Error_empty_prompt", `E.Generate<"", 2>`, JSON.stringify("Error: the prompt is empty"));

writeFileSync(
  new URL("tests/types/engine.gen.ts", root),
  `// Generated by scripts/gen-engine-tests.ts. Do not edit.
import type * as E from "../../src/engine/index.ts";
import type { ToS } from "../../src/num/ustr.ts";
import type { Equal, Expect } from "../../src/util.ts";

${checks.join("\n")}

// @ts-expect-error Seeds must be literal integers within the model's noise table.
export type InvalidSeed = E.Generate<"Once", 3, "sample", ${p.config.block_size}>;
`,
);
console.log(`wrote ${checks.length} checks`);
