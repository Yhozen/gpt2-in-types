// Generates tests/types/ops.gen.ts: random cases for every type-level op, with
// the expected values computed by the runtime reference (src/reference/fixed.ts).
// The type checker passes only if every op matches the reference digit for digit.
// Run: node scripts/gen-op-tests.ts [seed]
import { writeFileSync } from "node:fs";
import * as ref from "../src/reference/fixed.ts";

let seed = Number(process.argv[2] ?? 1);
const rand = () => (seed = (seed * 1103515245 + 12345) % 2 ** 31) / 2 ** 31;
const int = (max: number) => BigInt(Math.round((rand() * 2 - 1) * max));
const vec = (n: number, max: number) => Array.from({ length: n }, () => int(max));

export const num = (v: bigint): string =>
  (v < 0n ? "-" : "") + (v < 0n ? -v : v).toString().split("").reverse().join("");
const tuple = (v: bigint[]) => `[${v.map((x) => `"${num(x)}"`).join(", ")}]`;

const lines: string[] = [];
let n = 0;
const expect = (actual: string, expected: string) =>
  lines.push(`export type T${n++} = Expect<Equal<${actual}, ${expected}>>;`);

for (let i = 0; i < 40; i++) {
  const r = int(9000);
  const x = r < 0n ? r : -r;
  expect(`Exp<"${num(x)}">`, `"${num(ref.exp(x))}"`);
}
for (const x of [0n, -1n, -7999n, -8000n, -12345n])
  expect(`Exp<"${num(x)}">`, `"${num(ref.exp(x))}"`);
for (let i = 0; i < 40; i++) {
  const x = int(i < 20 ? 3000 : 12000);
  expect(`Gelu<"${num(x)}">`, `"${num(ref.gelu(x))}"`);
}
for (let i = 0; i < 40; i++) {
  const a = int(10 ** (1 + (i % 9)));
  const b = int(10 ** (1 + (i % 5))) || 7n;
  expect(`DivRound<"${num(a)}", "${num(b)}">`, `"${num(ref.divRound(a, b))}"`);
}
for (let i = 0; i < 30; i++) {
  const v = int(10 ** (1 + (i % 10)));
  const m = v < 0n ? -v : v;
  expect(`ISqrt<"${num(m)}">`, `"${num(ref.isqrt(m))}"`);
}
for (let i = 0; i < 4; i++) {
  const x = vec(32, 3000),
    g = vec(32, 1500),
    b = vec(32, 300);
  expect(`LayerNorm<${tuple(x)}, ${tuple(g)}, ${tuple(b)}>`, tuple(ref.layerNorm(x, g, b)));
}
for (let i = 1; i < 12; i++) {
  const s = vec(i, 6000);
  expect(`Softmax<${tuple(s)}>`, tuple(ref.softmax(s)));
  expect(`Argmax<${tuple(s)}>`, `${ref.argmax(s)}`);
}
{
  const w = Array.from({ length: 8 }, () => vec(32, 400)),
    x = vec(32, 3000),
    b = vec(8, 100);
  expect(
    `MatVec<[${w.map(tuple).join(", ")}], ${tuple(x)}, ${tuple(b)}>`,
    tuple(ref.matvec(w, x, b)),
  );
}

writeFileSync(
  new URL("../tests/types/ops.gen.ts", import.meta.url),
  `// Generated by scripts/gen-op-tests.ts. Do not edit.
import type { Argmax, Exp, Gelu, LayerNorm, MatVec, Softmax } from "../../src/gpt2/ops.ts";
import type { DivRound, ISqrt } from "../../src/num/index.ts";
import type { Equal, Expect } from "../../src/util.ts";

${lines.join("\n")}
`,
);
console.log(`wrote ${n} cases`);
