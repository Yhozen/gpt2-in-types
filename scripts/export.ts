// Converts model/weights.json (float, from scripts/train.py) into
// src/model/weights.ts: the fixed-point model as one TypeScript type.
// Run: node scripts/export.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { loadFloat, quantize } from "../src/reference/quantize.ts";

/** bigint -> little-endian Num string literal. */
export const num = (v: bigint): string =>
  `"${v < 0n ? "-" : ""}${(v < 0n ? -v : v).toString().split("").reverse().join("")}"`;
const vec = (v: bigint[]) => `[${v.map(num).join(", ")}]`;
const mat = (m: bigint[][], indent: string) =>
  `[\n${m.map((r) => `${indent}  ${vec(r)},`).join("\n")}\n${indent}]`;

const model = quantize(loadFloat());
const { n_layer, n_head, n_embd, block_size } = model.config;
const hd = n_embd / n_head;
const heads = <T>(rows: T[], offset: number): T[][] =>
  Array.from({ length: n_head }, (_, h) => rows.slice(offset + h * hd, offset + (h + 1) * hd));
const headMats = (m: bigint[][][], indent: string) =>
  `[\n${m.map((x) => `${indent}  ${mat(x, `${indent}  `)},`).join("\n")}\n${indent}]`;
const headVecs = (v: bigint[][]) => `[${v.map(vec).join(", ")}]`;

const layers = model.layers.map((L) => {
  const i = "      ";
  return `    {
      ln1g: ${vec(L.ln1g)};
      ln1b: ${vec(L.ln1b)};
      qW: ${headMats(heads(L.attnW, 0), i)};
      qB: ${headVecs(heads(L.attnB, 0))};
      kW: ${headMats(heads(L.attnW, n_embd), i)};
      kB: ${headVecs(heads(L.attnB, n_embd))};
      vW: ${headMats(heads(L.attnW, 2 * n_embd), i)};
      vB: ${headVecs(heads(L.attnB, 2 * n_embd))};
      projW: ${mat(L.projW, i)};
      projB: ${vec(L.projB)};
      ln2g: ${vec(L.ln2g)};
      ln2b: ${vec(L.ln2b)};
      fcW: ${mat(L.fcW, i)};
      fcB: ${vec(L.fcB)};
      mlpW: ${mat(L.mlpW, i)};
      mlpB: ${vec(L.mlpB)};
    },`;
});

const out = `// Generated by scripts/export.ts from model/weights.json. Do not edit.
//
// A ${n_layer}-layer, ${n_head}-head, ${n_embd}-dim GPT-2 trained on Tiny Shakespeare (characters).
// Every weight is a fixed-point number at scale 10^3, written as a little-endian
// digit string: "-5321" is -1.235. The 1/sqrt(head_dim) attention scale is folded
// into the query weights, and Q/K/V are split per head.

export type Model = {
  nLayer: ${n_layer};
  blockSize: ${block_size};
  vocab: [${model.vocab.map((c) => JSON.stringify(c)).join(", ")}];
  charToId: { ${model.vocab.map((c, i) => `${JSON.stringify(c)}: ${i}`).join("; ")} };
  wte: ${mat(model.wte, "  ")};
  wpe: ${mat(model.wpe, "  ")};
  layers: [
${layers.join("\n")}
  ];
  lnfG: ${vec(model.lnfG)};
  lnfB: ${vec(model.lnfB)};
};
`;

mkdirSync(new URL("../src/model/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/model/weights.ts", import.meta.url), out);
console.log(`wrote src/model/weights.ts (${(out.length / 1024).toFixed(0)} KiB)`);
