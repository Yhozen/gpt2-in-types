// Generate text with GPT-2 running inside the TypeScript type checker.
//
//   node scripts/generate.ts "ROMEO:" 16        # writes .run/clock.ts, runs tsrs, prints the text
//   node scripts/generate.ts "ROMEO:" 16 --out examples/romeo.ts
//                                              # writes a committed example that asserts the output
//
// The clock file is a chain of `type S{n+1} = Step<Model, S{n}>` statements; the
// checker evaluates them in order, each one a single tick of the model. The
// result surfaces as a type error on purpose: the generated text is the type
// the checker could not assign `0` to.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { ticksFor } from "../src/gpt2/model.ts";
import { generate } from "../src/reference/fixed.ts";
import { generateFloat } from "../src/reference/float.ts";
import { decode, encode, loadFloat, quantize } from "../src/reference/quantize.ts";

const args = process.argv.slice(2);
const outIdx = args.indexOf("--out");
const out = outIdx >= 0 ? args.splice(outIdx, 2)[1]! : undefined;
const prompt = args[0] ?? "ROMEO:";
const n = Number(args[1] ?? 16);

const root = resolve(import.meta.dirname, "..");
const float = loadFloat();
const model = quantize(float);
const ids = encode(model.vocab, prompt);
const expected = decode(model.vocab, generate(model, ids, n));
const floatText = decode(model.vocab, generateFloat(float, ids, n));
const ticks = ticksFor(ids.length, n, model.config.n_layer, model.config.n_head);

const file = resolve(root, out ?? ".run/clock.ts");
const rel = (p: string) => {
  const r = relative(dirname(file), resolve(root, p));
  return r.startsWith(".") ? r : `./${r}`;
};
const lines = [
  `// Generated by scripts/generate.ts. GPT-2 runs in the type checker, one tick per statement.`,
  `import type { Init, Output, Step } from "${rel("src/gpt2/model.ts")}";`,
  `import type { Model } from "${rel("src/model/weights.ts")}";`,
  out ? `import type { Equal, Expect } from "${rel("src/util.ts")}";` : "",
  ``,
  `type S0 = Init<Model, ${JSON.stringify(prompt)}, ${n}>;`,
  ...Array.from({ length: ticks }, (_, i) => `type S${i + 1} = Step<Model, S${i}>;`),
  ``,
  `export type Text = Output<Model, S${ticks}>;`,
  out
    ? `export type Check = Expect<Equal<Text, ${JSON.stringify(expected)}>>;`
    : `// Deliberate error: the message shows the generated text.\nexport const text: Text = 0;`,
  ``,
];
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, lines.filter((l, i) => l !== "" || i > 3).join("\n"));
if (out) {
  console.log(`wrote ${relative(root, file)} (${ticks} ticks)`);
  process.exit(0);
}

writeFileSync(
  resolve(root, ".run/tsconfig.json"),
  JSON.stringify(
    {
      extends: "../tsconfig.json",
      compilerOptions: { noErrorTruncation: true },
      files: ["clock.ts"],
    },
    null,
    2,
  ),
);

console.log(`prompt: ${JSON.stringify(prompt)}, ${n} tokens, ${ticks} ticks`);
const t0 = performance.now();
let output = "";
try {
  output = execFileSync(
    resolve(root, "node_modules/.bin/tsrs"),
    ["-p", ".run", "--fast", "--extendedDiagnostics"],
    {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 1 << 26,
    },
  );
} catch (e) {
  output = (e as { stdout: string }).stdout;
}
const seconds = ((performance.now() - t0) / 1000).toFixed(1);
const match = [...output.matchAll(/is not assignable to type '("(?:[^"\\]|\\.)*")'/g)].at(-1);
if (!match) {
  console.error(output.slice(0, 4000));
  process.exit(1);
}
const text = JSON.parse(match[1]!) as string;
const stat = (k: string) => output.match(new RegExp(`${k}:\\s+(\\S+)`))?.[1];

console.log(
  `\n--- type checker (${seconds}s, ${stat("Instantiations")} instantiations, ${stat("Memory used")}) ---`,
);
console.log(text);
console.log(`\n--- matches fixed-point reference: ${text === expected ? "yes" : "NO"} ---`);
if (text !== expected) console.log(expected);
console.log(`--- float64 model ${floatText === expected ? "agrees" : "differs"} ---`);
if (floatText !== expected) console.log(floatText);
process.exit(text === expected ? 0 : 1);
