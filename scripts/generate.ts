// Run GPT-2 in the type checker and print the text.
//
//   node scripts/generate.ts "Once upon a time" 24            # seeded sampling (T = 0.6)
//   node scripts/generate.ts "Once upon a time" 24 --greedy   # argmax
//   node scripts/generate.ts "Once upon a time" 24 --out examples/story.ts [--chunk 2]
//
// The first two write .run/hover.ts (`type Text = Generate<...>`), hover `Text`
// through the tsrs language server (scripts/hover.ts) and compare the result
// with the integer reference (src/reference/int.ts).
//
// --out writes a CLI-checked example instead: the same generation split into
// statements of --chunk positions each (default 2; the CLI allows ~5M type
// instantiations per statement, see Refuel in src/engine), plus an
// assertion that the output equals the reference.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { decode, encode, generate, type Program } from "../src/reference/int.ts";
import { hover } from "./hover.ts";

const ROOT = resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const greedy = args.includes("--greedy");
/** Value of `--name value`, removed from the positional arguments. */
const valued = new Set<number>();
const option = (name: string) => {
  const i = args.indexOf(name);
  if (i < 0) return undefined;
  valued.add(i + 1);
  return args[i + 1];
};
const out = option("--out");
// Positions per statement: each costs 1-2.5M instantiations at the default size.
const chunk = Number(option("--chunk") ?? 2);
const positional = args.filter((a, i) => !a.startsWith("--") && !valued.has(i));
const prompt = positional[0] ?? "Once upon a time";
const n = Number(positional[1] ?? 24);
const mode = greedy ? "greedy" : "sample";
const modeArg = greedy ? `, "greedy"` : "";

const program = JSON.parse(readFileSync(resolve(ROOT, "model/program.json"), "utf8")) as Program;
const expected = decode(program, generate(program, encode(program, prompt), n, mode));
const quote = (s: string) => JSON.stringify(s);

if (out) {
  const file = resolve(ROOT, out);
  const rel = (p: string) => {
    const r = relative(dirname(file), resolve(ROOT, p));
    return r.startsWith(".") ? r : `./${r}`;
  };
  const lines = [
    `// Generated by scripts/generate.ts. Checked by \`vp run examples\` (tsrs CLI).`,
    `// The CLI allows ~5M type instantiations per statement, so the model runs`,
    `// ${chunk} positions per statement. In the editor, hover Text in examples/hover.ts.`,
    `import type { Advance, Output, Start } from "${rel("src/engine/index.ts")}";`,
    `import type { Equal, Expect } from "${rel("src/util.ts")}";`,
    ``,
    `type S0 = Start<${quote(prompt)}>;`,
  ];
  const positions = prompt.length + n - 1;
  let step = 0;
  for (let done = 0; done < positions; done += chunk, step++) {
    lines.push(
      `type S${step + 1} = Advance<S${step}, ${Math.min(chunk, positions - done)}${modeArg}>;`,
    );
  }
  lines.push(
    ``,
    `export type Text = Output<S${step}>;`,
    `export type Check = Expect<Equal<Text, ${quote(expected)}>>;`,
    ``,
  );
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, lines.join("\n"));
  console.log(`wrote ${relative(ROOT, file)}: ${quote(expected)}`);
} else {
  const file = resolve(ROOT, ".run/hover.ts");
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(
    file,
    `import type { Generate } from "../src/engine/index.ts";\n\nexport type Text = Generate<${quote(prompt)}, ${n}${modeArg}>;\n`,
  );
  console.log(`prompt ${quote(prompt)}, ${n} tokens, ${mode}: hovering Text via tsrs --lsp ...`);
  const result = await hover(file, "Text");
  const match = /type Text = ("(?:[^"\\]|\\.)*")/.exec(result.text);
  const text = match ? (JSON.parse(match[1]!) as string) : undefined;
  console.log(`\n--- hover (${result.seconds.toFixed(2)}s) ---\n${text ?? result.text}`);
  console.log(`\n--- matches the integer reference: ${text === expected ? "yes" : "NO"} ---`);
  if (text !== expected) {
    console.log(expected);
    process.exitCode = 1;
  }
}
