// Generates the digit lookup tables used by the type-level arithmetic in src/num.
// Run: node scripts/gen-tables.ts
import { writeFileSync } from "node:fs";

const add: string[] = [];
const sub: string[] = [];
const mul: string[] = [];
const cmp: string[] = [];
for (let a = 0; a < 10; a++) {
  for (let b = 0; b < 10; b++) {
    cmp.push(`  "${a}${b}": "${a < b ? "<" : a > b ? ">" : "="}";`);
    for (const c of [0, 1]) {
      const s = a + b + c;
      add.push(`  "${a}${b}${c}": "${s % 10}${Math.floor(s / 10)}";`);
      const d = a - b - c;
      sub.push(`  "${a}${b}${c}": "${(d + 10) % 10}${d < 0 ? 1 : 0}";`);
    }
    for (let c = 0; c < 10; c++) {
      const p = a * b + c;
      mul.push(`  "${a}${b}${c}": "${p % 10}${Math.floor(p / 10)}";`);
    }
  }
}

const out = `// Generated by scripts/gen-tables.ts. Do not edit.
// Keys are digit triples \`\${a}\${b}\${carry}\`; values are \`\${digit}\${carryOut}\`.

/** a + b + carry */
export type AddTable = {
${add.join("\n")}
};

/** a - b - borrow */
export type SubTable = {
${sub.join("\n")}
};

/** a * b + carry */
export type MulTable = {
${mul.join("\n")}
};

/** compare digits a and b */
export type CmpTable = {
${cmp.join("\n")}
};
`;
writeFileSync(new URL("../src/num/tables.ts", import.meta.url), out);

// exp() tables for src/gpt2/ops.ts, shared with the runtime reference.
const { EXP_TABLES } = await import("../src/reference/fixed.ts");
const num = (v: bigint) => v.toString().split("").reverse().join("");
const table = (name: string, doc: string, values: bigint[]) =>
  `/** ${doc} */\nexport type ${name} = {\n${values.map((v, i) => `  "${i}": "${num(v)}"; // ${v}`).join("\n")}\n};\n`;
writeFileSync(
  new URL("../src/gpt2/exp-table.ts", import.meta.url),
  `// Generated by scripts/gen-tables.ts. Do not edit.
// Values are little-endian Nums at scale 10^6.

${table("ExpInt", "e^-i", EXP_TABLES.int)}
${table("ExpD1", "e^-(d/10)", EXP_TABLES.d1)}
${table("ExpD2", "e^-(d/100)", EXP_TABLES.d2)}
${table("ExpD3", "e^-(d/1000)", EXP_TABLES.d3)}`,
);
